#!/usr/bin/env python3
"""
Build the SCARA Digital Twin phone app (Android APK) from app/ui + app/android.

    python3 tools/build_app.py                 # -> app/SCARA_Digital_Twin_v3.apk
    python3 tools/build_app.py --meshes-only   # only refresh app/ui/meshes.js (for testing in a browser)

The app is a small Android WebView shell (app/android, smali) around the web UI in
app/ui (HTML + JavaScript + three.js).  The robot meshes are packed into
app/ui/meshes.js (16-bit quantised) - if meshes/shoulder_name.stl exists, the name
plate is packed too, so the app shows the same robot as Gazebo / MuJoCo / RViz.

Try the UI on a PC without building anything: open app/ui/index.html in Chrome
(or serve the folder: python3 -m http.server -d app/ui 8000).

Building the APK needs Java 11+ and two jar files (put them in ~/tools or pass them):
  apktool      https://github.com/iBotPeaches/Apktool/releases        (apktool.jar)
  apk signer   https://github.com/patrickfav/uber-apk-signer/releases (uber-apk-signer.jar)
"""
import argparse
import base64
import os
import shutil
import struct
import subprocess
import sys
import tempfile

import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
UI = os.path.join(ROOT, 'app', 'ui')
VERSION = '3.3.0'
ANDROID = os.path.join(ROOT, 'app', 'android')
MESHES = ['base_link', 'column_link', 'shoulder_link', 'forearm_link', 'wrist_link',
          'left_finger_link', 'right_finger_link', 'camera_link', 'shoulder_name']


def load_stl(path):
    b = open(path, 'rb').read()
    n = struct.unpack('<I', b[80:84])[0]
    if 84 + n * 50 == len(b):
        a = np.frombuffer(b[84:84 + n * 50], dtype=np.dtype([('n', '<f4', 3), ('v', '<f4', (3, 3)), ('a', '<u2')]))
        return a['v'].reshape(-1, 3).astype(np.float64)
    pts = [list(map(float, l.split()[1:4])) for l in b.decode('latin1').splitlines() if l.strip().startswith('vertex')]
    return np.array(pts, np.float64)


def pack_meshes(out=os.path.join(UI, 'meshes.js')):
    parts, total = [], 0
    for name in MESHES:
        path = os.path.join(ROOT, 'meshes', name + '.stl')
        if not os.path.exists(path):
            continue
        v = load_stl(path)
        lo, hi = v.min(0), v.max(0)
        span = np.maximum(hi - lo, 1e-9)
        q = np.round((v - lo) / span * 65535).astype(np.uint16)
        data = base64.b64encode(q.tobytes()).decode()
        total += len(data)
        parts.append(f'"{name}":{{"min":[{lo[0]:.4f},{lo[1]:.4f},{lo[2]:.4f}],'
                     f'"span":[{span[0]:.4f},{span[1]:.4f},{span[2]:.4f}],"data":"{data}"}}')
    with open(out, 'w') as fh:
        fh.write('/* GENERATED by tools/build_app.py from meshes/*.stl (mm, 16-bit) - do not edit */\n')
        fh.write('window.SCARA_MESHES={' + ','.join(parts) + '};\n')
    print(f'wrote {out} ({total / 1e6:.1f} MB, {len(parts)} meshes)')


def write_scene(out=os.path.join(UI, 'scene.js')):
    """Cell geometry for the app's offline demo (the live app gets it from the PC)."""
    import json
    sys.path[:0] = [os.path.join(ROOT, d) for d in ('common', 'mujoco', 'gazebo', 'real_robot', 'server', 'gesture_control')]
    import scara_scene as S
    from scara_twin_server import scene_info
    sc = scene_info()
    sc['ready_xy'] = list(S.READY_XY)
    sc['z_travel'] = S.Z_TRAVEL
    with open(out, 'w') as fh:
        fh.write('/* GENERATED by tools/build_app.py from common/scara_scene.py - do not edit */\n')
        fh.write('window.SCARA_SCENE=' + json.dumps(sc) + ';\n')
    print('wrote', out)


def write_brand(out=os.path.join(UI, 'brand.js')):
    """The name for the app's header, start screen and About: only when the arm has a name
    (meshes/shoulder_name.stl from tools/make_name_mesh.py); without that file there is none."""
    import json
    paint = os.path.join(ROOT, 'meshes', 'shoulder_name.stl')
    name = None
    if os.path.exists(paint):
        head = open(paint, 'rb').read(80)
        name = head[5:].split(b'\0')[0].decode('utf-8', 'ignore').strip() if head.startswith(b'name:') else None
    with open(out, 'w') as fh:
        fh.write('/* GENERATED by tools/build_app.py - the name comes from meshes/shoulder_name.stl */\n')
        fh.write('window.SCARA_BRAND=' + json.dumps({'name': name or None, 'version': VERSION}) + ';\n')
    print('wrote', out, f'(name: {name or "none"})')


def find_jar(name, given):
    for c in [given, os.path.join(os.path.expanduser('~'), 'tools', name), os.path.join(ROOT, 'tools', name)]:
        if c and os.path.exists(c):
            return c
    raise SystemExit(f'{name} not found - download it (see the top of this file) and pass --{name.split("-")[0].split(".")[0]}')


def build_apk(out, apktool, signer):
    with tempfile.TemporaryDirectory() as tmp:
        proj = os.path.join(tmp, 'app')
        shutil.copytree(ANDROID, proj)
        shutil.copytree(UI, os.path.join(proj, 'assets', 'ui'))
        unsigned = os.path.join(tmp, 'app-unsigned.apk')
        subprocess.run(['java', '-jar', apktool, 'b', '-q', '-f', '-o', unsigned, proj], check=True)
        subprocess.run(['java', '-jar', signer, '-a', unsigned, '-o', tmp, '--allowResign'], check=True,
                       stdout=subprocess.DEVNULL)
        signed = [f for f in os.listdir(tmp) if f.endswith('.apk') and 'Signed' in f]
        if not signed:
            raise SystemExit('signing failed')
        shutil.copy(os.path.join(tmp, signed[0]), out)
    print('wrote', out, f'({os.path.getsize(out) / 1e6:.1f} MB)')


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--meshes-only', action='store_true')
    ap.add_argument('--out', default=os.path.join(ROOT, 'app', 'SCARA_Digital_Twin_v3.apk'))
    ap.add_argument('--apktool', default=None, help='path to apktool.jar')
    ap.add_argument('--signer', default=None, help='path to uber-apk-signer.jar')
    a = ap.parse_args()
    pack_meshes()
    write_scene()
    write_brand()
    if a.meshes_only:
        return
    build_apk(a.out, find_jar('apktool.jar', a.apktool), find_jar('uber-apk-signer.jar', a.signer))


if __name__ == '__main__':
    sys.exit(main())
